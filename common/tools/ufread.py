#!/usr/bin/env python3
"""Writes ufread.pd: [ufread <file> <default> <text>] reads a user bank file into the [text
define <text>] it names, from the folder of the patch that holds it; when the file is not there
(a fresh checkout: user banks are not in git, so git pull never touches them) it reads <default>
instead. The first save writes <file>. Needs Pd 0.52 or newer ([file isfile], [pdcontrol]).

usage: python3 common/tools/ufread.py <out.pd>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import patchwriter as G   # noqa: E402


def write(path):
    p = G.P(None, 620, 330)
    p.note("ufread <file> <default> <text>: bang -> read <file> (beside this patch) into [text define "
           "<text>] or, when it is missing, <default>. Generated by common/tools/ufread.py.", 10, 6)
    inl = p.add("inlet", 10, 50)
    tb = p.add("t b b", 10, 80); p.con(inl, 0, tb, 0)
    dm = p.msg("dir", 10, 110); p.con(tb, 0, dm, 0)
    pc = p.add("pdcontrol", 10, 140); p.con(dm, 0, pc, 0)
    mf = p.add("makefilename %s/$1", 10, 170); p.con(pc, 0, mf, 0)
    fi = p.add("file isfile", 10, 200); p.con(mf, 0, fi, 0)
    tb1 = p.add("t b", 10, 215); p.con(fi, 0, tb1, 0)
    s1 = p.add("symbol $1", 10, 230); p.con(tb1, 0, s1, 0)
    s2 = p.add("symbol $2", 120, 230); p.con(fi, 1, s2, 0)
    lp = p.add("list prepend read", 10, 260); p.con(s1, 0, lp, 0); p.con(s2, 0, lp, 0)
    lt = p.add("list trim", 10, 290); p.con(lp, 0, lt, 0)
    sd = p.add("s $3", 10, 320); p.con(lt, 0, sd, 0)
    with open(path, "w") as fh:
        fh.write("\n".join(p.lines(top=True)) + "\n")


if __name__ == "__main__":
    write(sys.argv[1])
    print("wrote", sys.argv[1])
