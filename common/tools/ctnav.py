#!/usr/bin/env python3
"""Pad translator for instruments that keep their user bank in Pd (pdoly8~, tx81zn~).

juno~, d50~ and cz4~ understand the pad messages themselves. pdoly8~ and tx81zn~ keep their
factory presets and their user bank in Pd files (the same files the editors use), so
[<x>nav] turns the pad messages into what the instrument understands:

    presetstep <n>   the factory sound after (or before) the one recalled last, wrapping
    userstep <n>     the same in the user bank; an empty slot ("-") only shows "empty"
    init             the instrument's init sound
    save             asks the instrument for its sound, puts it into the user slot recalled
                     last and writes the user bank file

Left inlet: those messages (from the pads, [<x>pads]); anything else goes through unchanged. Right inlet: the instrument's message
outlet (its sound for save, its patch name for the display).
Left outlet: to the instrument. Right outlet: display <title> <value> (for [lkdisplay]),
the same lines juno~, d50~ and cz4~ send themselves; the instrument's own display lines (a
setting turned) come in at the right inlet and go out here too, so [lkdisplay] needs only
this outlet.

The user bank file is read again before every userstep and save, so a save in the editor
counts at once, and the editor reads the file the translator wrote when it loads it.

write(path, title, cfg), cfg:
  factory_count   number of factory sounds
  factory_msg     message recalling factory sound $1 (e.g. "pgm $1"), or
  factory_file    a preset file beside the abstraction, one sound per line, sent as
                  "<recall> <line>" (recall below)
  user_file       the user bank file beside the abstraction ("-" = empty slot); not in git
  user_default    read instead while user_file does not exist yet (ufread.pd beside it)
  user_slots      its number of slots (64: shown as 11 ... 88)
  get_msg         asks the instrument for its sound ("getvoice", "dump")
  reply           the selector of the answer ("voicedata", "dump"); its arguments are the line
  recall          the selector a user line is sent with ("voicedata", "dump")
  init_msg        the init message ("init", "defaults")
  name            the selector the instrument reports its patch name with ("voice"), or None:
                  then the display shows "-" as value
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import patchwriter as G   # noqa: E402

SAVE_TIMEOUT_MS = 500


def build(title, cfg):
    N, S = cfg["factory_count"], cfg["user_slots"]
    ufile = cfg["user_file"]
    named = cfg.get("name") is not None
    p = G.P(None, 1200, 900)
    p.note(f"{title}: pad translator - presetstep <n>, userstep <n>, init, save (left inlet) -> "
           f"the instrument (left outlet); display <title> <value> (right outlet). Right inlet: the "
           f"instrument's messages. User bank: {ufile} beside this file, {S} slots, read again before "
           f"every userstep and save. Generated by common/tools/ctnav.py.", 10, 6)
    inl = p.add("inlet", 10, 60)
    inr = p.add("inlet", 700, 60)
    pd_ = p.add("route display", 1000, 90); p.con(inr, 0, pd_, 0)
    # rebuilt with list prepend, not a message box with $1 $2 (which on the Bela turned a value into
    # 0 and fails on a line with a single atom)
    pdl = p.add("list prepend display", 1000, 115); p.con(pd_, 0, pdl, 0)
    pdm = p.add("list trim", 1000, 140); p.con(pdl, 0, pdm, 0)
    out = p.add("outlet", 10, 860)
    dout = p.add("outlet", 700, 860)
    p.con(pdm, 0, dout, 0)
    r = p.add("route presetstep userstep init save savearm saveslot savecancel", 10, 90); p.con(inl, 0, r, 0)
    p.con(r, 7, out, 0)          # everything else (the instrument's own pads) goes through

    # ---- display: value into the right inlet of [pack s s] first, then the title
    pk = p.add("pack s s", 700, 760)
    lpd = p.add("list prepend display", 700, 790); p.con(pk, 0, lpd, 0)
    ltd = p.add("list trim", 700, 820); p.con(lpd, 0, ltd, 0); p.con(ltd, 0, dout, 0)
    tsym = p.add("symbol", 700, 730); p.con(tsym, 0, pk, 0)          # the title of the last action
    dash = p.msg("symbol -", 860, 700); p.con(dash, 0, pk, 1)

    def show_now(src, outn=0):
        """value "-" (no name) and the title: display at once"""
        t = p.add("t b b", 860, 640); p.con(src, outn, t, 0)
        p.con(t, 1, dash, 0); p.con(t, 0, tsym, 0)
        return t

    # pending: a recall that waits for the instrument's patch name
    pend = p.add("spigot", 1000, 520)
    one = p.msg("1", 1060, 460); zero = p.msg("0", 1100, 460)
    p.con(one, 0, pend, 1); p.con(zero, 0, pend, 1)
    if named:
        rn = p.add(f"route {cfg['name']}", 1000, 430); p.con(inr, 0, rn, 0)
        ln = p.add("list", 1000, 460); p.con(rn, 0, ln, 0); p.con(ln, 0, pend, 0)
        sn = p.add("symbol", 1000, 550); p.con(pend, 0, sn, 0)
        tn = p.add("t b s b", 1000, 580); p.con(sn, 0, tn, 0)
        p.con(tn, 2, zero, 0); p.con(tn, 1, pk, 1); p.con(tn, 0, tsym, 0)

    def recall_done(src, outn=0):
        """after the title is set: wait for the name, or show it now"""
        if named:
            p.con(src, outn, one, 0)
        else:
            show_now(src, outn)

    # ---- presetstep [n]: default 1. Right to left: the one recalled last, the title, the
    # display (now, or the gate for the name the instrument reports during the recall), the recall
    la = p.add("list append 1", 10, 130); p.con(r, 0, la, 0)
    ls = p.add("list split 1", 10, 160); p.con(la, 0, ls, 0)
    ex = p.add(f"expr (($f1 + $f2) % {N} + {N}) % {N}", 10, 190); p.con(ls, 0, ex, 0)
    t4 = p.add("t f b f f", 10, 220); p.con(ex, 0, t4, 0)
    p.con(t4, 3, ex, 1)
    mf = p.add("makefilename Preset\\ %d", 120, 260); p.con(t4, 2, mf, 0); p.con(mf, 0, tsym, 1)
    recall_done(t4, 1)
    if "factory_msg" in cfg:
        fm = p.msg(cfg["factory_msg"], 10, 300); p.con(t4, 0, fm, 0); p.con(fm, 0, out, 0)
    else:
        fdef = p.add("text define $0-factory", 300, 330)
        lb = p.add("loadbang", 300, 270)
        rdf = p.msg(f"read {cfg['factory_file']}", 300, 300); p.con(lb, 0, rdf, 0); p.con(rdf, 0, fdef, 0)
        tgf = p.add("text get $0-factory", 10, 300); p.con(t4, 0, tgf, 0)
        lpf = p.add(f"list prepend {cfg['recall']}", 10, 330); p.con(tgf, 0, lpf, 0)
        ltf = p.add("list trim", 10, 360); p.con(lpf, 0, ltf, 0); p.con(ltf, 0, out, 0)

    # ---- user bank
    udef = p.add("text define $0-user", 400, 520)
    lbu = p.add("loadbang", 400, 460)
    rdu = p.add(f"ufread {ufile} {cfg.get('user_default', ufile)} $0-user", 400, 490)
    p.con(lbu, 0, rdu, 0)
    wru = p.msg(f"write {ufile}", 520, 490); p.con(wru, 0, udef, 0)
    # the slot recalled last and its label (11 ... 88)
    uslot = p.add("f", 300, 560)
    ulab = p.add("expr int($f1 / 8) * 10 + $f1 % 8 + 11", 300, 590); p.con(uslot, 0, ulab, 0)
    umf = p.add("makefilename User\\ %d", 300, 620); p.con(ulab, 0, umf, 0)
    usym = p.add("symbol", 300, 650); p.con(umf, 0, usym, 1)
    lbs = p.add("loadbang", 300, 500); p.con(lbs, 0, uslot, 0)       # "User 11" until a step
    # userstep [n]
    la2 = p.add("list append 1", 120, 400); p.con(r, 1, la2, 0)
    ls2 = p.add("list split 1", 120, 430); p.con(la2, 0, ls2, 0)
    ex2 = p.add(f"expr (($f1 + $f2) % {S} + {S}) % {S}", 120, 460); p.con(ls2, 0, ex2, 0)
    t5 = p.add("t f b b f", 120, 490); p.con(ex2, 0, t5, 0)
    p.con(t5, 3, ex2, 1); p.con(t5, 3, uslot, 0)                      # last slot, its label
    p.con(t5, 2, usym, 0)                                              # label -> title (via usym)
    p.con(usym, 0, tsym, 1)
    p.con(t5, 1, rdu, 0)                                               # read the file again
    tgu = p.add("text get $0-user", 120, 540); p.con(t5, 0, tgu, 0)
    ltu = p.add("list trim", 120, 570); p.con(tgu, 0, ltu, 0)
    rdash = p.add("route -", 120, 600); p.con(ltu, 0, rdash, 0)
    emp = p.add("t b b", 10, 640); p.con(rdash, 0, emp, 0)
    em = p.msg("symbol empty", 60, 670); p.con(emp, 1, em, 0); p.con(em, 0, pk, 1); p.con(emp, 0, tsym, 0)
    tl = p.add("t a b", 200, 640); p.con(rdash, 1, tl, 0)
    recall_done(tl, 1)
    lpu = p.add(f"list prepend {cfg['recall']}", 200, 680); p.con(tl, 0, lpu, 0)
    ltu2 = p.add("list trim", 200, 710); p.con(lpu, 0, ltu2, 0); p.con(ltu2, 0, out, 0)

    # ---- init
    ti = p.add("t b b b", 520, 130); p.con(r, 2, ti, 0)
    it = p.msg("symbol Init", 620, 160); p.con(ti, 2, it, 0); p.con(it, 0, tsym, 1)
    recall_done(ti, 1)
    im = p.msg(cfg["init_msg"], 520, 190); p.con(ti, 0, im, 0); p.con(im, 0, out, 0)

    # ---- store with a question (the pads): savearm shows "Store to?" and the slot recalled last,
    # saveslot <n> moves that slot, save then stores there, savecancel drops it
    a1 = p.msg("1", 1150, 70); a0 = p.msg("0", 1190, 70)              # armed / not
    # the target slot: [value $0-tsl]; shown as "Store to?" / "User NN"
    shw = p.add("t f f", 1150, 300)
    tset = p.add("value $0-tsl", 1250, 330); p.con(shw, 1, tset, 0)
    tlab = p.add("expr int($f1 / 8) * 10 + $f1 % 8 + 11", 1150, 330); p.con(shw, 0, tlab, 0)
    tmf = p.add("makefilename User\\ %d", 1150, 360); p.con(tlab, 0, tmf, 0)
    tq = p.add("t b s", 1150, 390); p.con(tmf, 0, tq, 0)
    p.con(tq, 1, pk, 1)
    sq = p.msg("symbol Store\\ to?", 1150, 420); p.con(tq, 0, sq, 0); p.con(sq, 0, pk, 0)
    # savearm: armed, the slot recalled last is the target
    sa = p.add("t b b", 1150, 130); p.con(r, 4, sa, 0)
    p.con(sa, 1, a1, 0)
    ul = p.add("f", 1150, 160); p.con(uslot, 0, ul, 1); p.con(sa, 0, ul, 0); p.con(ul, 0, shw, 0)
    # saveslot <n>: the target moves by n, wrapping
    ssl = p.add("t b f", 1300, 130); p.con(r, 5, ssl, 0)
    ex3 = p.add(f"expr (($f1 + $f2) % {S} + {S}) % {S}", 1300, 190); p.con(ssl, 1, ex3, 1)
    tget = p.add("value $0-tsl", 1300, 160); p.con(ssl, 0, tget, 0); p.con(tget, 0, ex3, 0)
    p.con(ex3, 0, shw, 0)
    # savecancel: not armed any more, "Store" / "cancelled"
    sc = p.add("t b b b", 1450, 130); p.con(r, 6, sc, 0)
    p.con(sc, 2, a0, 0)
    cv = p.msg("symbol cancelled", 1450, 160); p.con(sc, 1, cv, 0); p.con(cv, 0, pk, 1)
    cs_ = p.msg("symbol Store", 1450, 190); p.con(sc, 0, cs_, 0); p.con(cs_, 0, pk, 0)
    # save: when armed, the target first becomes the slot to store into
    sv = p.add("t b b", 520, 230); p.con(r, 3, sv, 0)
    sva = p.add("f", 600, 230); p.con(a1, 0, sva, 1); p.con(a0, 0, sva, 1)
    p.con(sv, 1, sva, 0)
    svs = p.add("sel 1", 600, 255); p.con(sva, 0, svs, 0)
    svt = p.add("t b b", 600, 280); p.con(svs, 0, svt, 0)
    tsv = p.add("value $0-tsl", 680, 305); p.con(svt, 1, tsv, 0); p.con(tsv, 0, uslot, 0)
    p.con(svt, 0, a0, 0)
    # ---- save: read the file, open the gate, ask; the answer goes into the slot
    ts = p.add("t b b b b", 520, 260); p.con(sv, 0, ts, 0)
    p.con(ts, 3, rdu, 0)
    gate = p.add("spigot", 700, 330)
    g1 = p.msg("1", 800, 290); g0 = p.msg("0", 840, 290)
    p.con(ts, 2, g1, 0); p.con(g1, 0, gate, 1); p.con(g0, 0, gate, 1)
    dl = p.add(f"del {SAVE_TIMEOUT_MS}", 880, 260); p.con(ts, 1, dl, 0); p.con(dl, 0, g0, 0)
    gm = p.msg(cfg["get_msg"], 520, 300); p.con(ts, 0, gm, 0); p.con(gm, 0, out, 0)
    rr = p.add(f"route {cfg['reply']}", 700, 270); p.con(inr, 0, rr, 0)
    lr = p.add("list", 700, 300); p.con(rr, 0, lr, 0); p.con(lr, 0, gate, 0)
    tr = p.add("t b l b", 700, 360); p.con(gate, 0, tr, 0)
    p.con(tr, 2, g0, 0); p.con(tr, 2, dl, 0)                           # close (stop the timeout)
    tset = p.add("text set $0-user", 700, 400); p.con(tr, 1, tset, 0); p.con(uslot, 0, tset, 1)
    p.con(tr, 0, wru, 0)
    # display: Stored / User NN
    tw = p.add("t b b", 860, 400); p.con(tr, 0, tw, 0)
    us2 = p.add("symbol", 960, 430); p.con(umf, 0, us2, 1)
    p.con(tw, 1, us2, 0); p.con(us2, 0, pk, 1)
    st = p.msg("symbol Stored", 860, 460); p.con(tw, 0, st, 0); p.con(st, 0, pk, 0)
    return p


def write(path, title, cfg):
    p = build(title, cfg)
    with open(path, "w") as fh:
        fh.write("\n".join(p.lines(top=True)) + "\n")
