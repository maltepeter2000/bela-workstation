#!/usr/bin/env python3
"""Control pads: the Launchkey's pads in Drum mode as buttons for an instrument.

With the Launchkey custom firmware (maltepeter2000/launchkey_firmware) the 16 pads send fixed
notes in rows on the Drums Channel (10 at the factory):

    top row     36 37 38 39 40 41 42 43
    bottom row  44 45 46 47 48 49 50 51

The same layout for every instrument (COMMON), so the hands learn it once; the instrument fills
its own pads (OWN) with what only it has:

    top row     36 factory +   37 user +   38 init (twice)   39-43 own
    bottom row  44 factory -   45 user -   46 save           47-51 own

The messages are the same in every instrument: presetstep 1 / -1 (the factory patch after or
before the one played last), userstep 1 / -1 (the same in the user bank), init (the init patch),
save (the playing sound into the user slot played or stored last, and the user bank written).
Each instrument answers with "display <title> <value>" for the Launchkey display.
layout(own) checks the instrument's own pads and returns the whole table.

write(path, title, table) makes the abstraction [<name> <channel>] (channel 0 or none
= 10): [notein] inside, a pad pressed on that channel -> its message at the outlet (to the
instrument). table: {note: "message"} or {note: ("twice", "message")} for a pad that has to be
pressed twice within a second (for what drops the edits). Inlet: channel <n>, leds.

Pad colours, the same in every instrument (by the pad's message, see color()):

    factory +/-  blue        user +/-  green       init  orange (flashing while armed)
    save         red (white for a moment when pressed)
    own pads     purple      free pads  off

The abstraction sends them with [noteout] on the pad channel (the firmware's pad LED protocol:
note = pad, velocity = colour + 32 * mode, 0 = the Launchkey's own LED; launchkey/README.md) at
load, on "leds", on a channel change and when the Launchkey asks for them (CC 3 = 127 on the pad
channel, sent when pad mode Drum is selected).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import patchwriter as G   # noqa: E402

TOP = list(range(36, 44))
BOTTOM = list(range(44, 52))

COMMON = {
    36: "presetstep 1", 44: "presetstep -1",
    37: "userstep 1", 45: "userstep -1",
    38: ("twice", "init"), 46: "save",
}
COMMON_TEXT = {36: "factory +", 44: "factory -", 37: "user +", 45: "user -", 38: "init (2x)", 46: "save"}
OWN = list(range(39, 44)) + list(range(47, 52))

# Launchkey pad LED palette (launchkey_firmware cfw/drum_pads.c): colour index, + 32 = flashing,
# + 64 = pulsing, 16 + n = colour n dimmed.
OFF, WHITE, RED, ORANGE, YELLOW, GREEN, CYAN, BLUE, PURPLE = range(9)
FLASH, PULSE = 32, 64
COLORS = {"presetstep": BLUE, "userstep": GREEN, "init": ORANGE, "save": RED}
OWN_COLOR = PURPLE
SAVE_ACK_MS = 600


def color(act):
    """LED velocity of a pad by its message (a string or ("twice", message))."""
    msg = act[1] if isinstance(act, tuple) else act
    return COLORS.get(msg.split()[0], OWN_COLOR)


def layout(own=None):
    """COMMON plus the instrument's own pads (39-43, 47-51)."""
    own = own or {}
    bad = [n for n in own if n not in OWN]
    assert not bad, f"pads {bad} are not free: the instrument's own pads are 39-43 and 47-51"
    t = dict(COMMON)
    t.update(own)
    return t


def write(path, title, table):
    p = G.P(None, 980, 760)
    p.note(f"{title}: control pads - the Launchkey's pads in Drum mode (notes 36-51, top row 36-43) on "
           "channel $1 (0 = 10, the Drums Channel) -> a message to the instrument. Inlet: channel <n>, "
           "leds (send the pad colours again). Generated by common/tools/ctpads.py.", 10, 6)
    lb = p.add("loadbang", 10, 40)
    ca = p.add("f $1", 10, 65); p.con(lb, 0, ca, 0)
    cd = p.add("expr if($f1 > 0, $f1, 10)", 10, 90); p.con(ca, 0, cd, 0)
    inl = p.add("inlet", 260, 40)
    rc = p.add("route channel leds", 260, 65); p.con(inl, 0, rc, 0); p.con(rc, 0, cd, 0)
    # --- pad LEDs: [noteout] on the pad channel, "note velocity" lists into [s $0-led]
    ly = 530
    p.note("pad LEDs: velocity = colour + 32 * mode (common/tools/ctpads.py, launchkey/README.md)", 10, ly - 25)
    lr = p.add("r $0-led", 10, ly)
    lu = p.add("unpack f f", 10, ly + 25); p.con(lr, 0, lu, 0)
    no = p.add("noteout", 10, ly + 55)
    p.con(lu, 1, no, 1); p.con(lu, 0, no, 0)
    chs = p.add("t f f", 10, 115); p.con(cd, 0, chs, 0)
    p.con(chs, 1, no, 2)
    allb = p.add("t b", 400, ly)
    p.con(chs, 0, allb, 0); p.con(rc, 1, allb, 0)
    full = {n: table.get(n) for n in TOP + BOTTOM}
    allm = p.msg(", ".join(f"{n} {color(a) if a is not None else OFF}" for n, a in full.items()), 400, ly + 30)
    p.con(allb, 0, allm, 0)
    sl = p.add("s $0-led", 400, ly + 90); p.con(allm, 0, sl, 0)
    # the Launchkey asks for the colours: CC 3 = 127 on the pad channel when pad mode Drum is selected
    cl = p.add("ctlin 3", 600, ly)
    cq = p.add("pack f f", 600, ly + 25); p.con(cl, 1, cq, 1); p.con(cl, 0, cq, 0)
    ce = p.add("expr $f1 > 0 && $f2 == $f3", 600, ly + 75)
    cu = p.add("unpack f f", 600, ly + 50); p.con(cq, 0, cu, 0)
    p.con(cu, 1, ce, 1); p.con(cu, 0, ce, 0); p.con(chs, 0, ce, 2)
    cs = p.add("sel 1", 600, ly + 100); p.con(ce, 0, cs, 0); p.con(cs, 0, allb, 0)
    ni = p.add("notein", 10, 130)
    pk = p.add("pack f f f", 10, 160)
    p.con(ni, 2, pk, 2); p.con(ni, 1, pk, 1); p.con(ni, 0, pk, 0)
    ok = p.add("expr $f2 > 0 && $f3 == $f4", 10, 190)
    up = p.add("unpack f f f", 10, 215)
    tl = p.add("t l l", 10, 240); p.con(pk, 0, tl, 0)
    p.con(tl, 1, up, 0)
    p.con(up, 0, ok, 0); p.con(up, 2, ok, 2); p.con(up, 1, ok, 1); p.con(cd, 0, ok, 3)
    # the note only when ok: [spigot] on the note
    sp = p.add("spigot", 120, 270); p.con(ok, 0, sp, 1)
    un = p.add("unpack f f f", 120, 245); p.con(tl, 0, un, 0); p.con(un, 0, sp, 0)
    notes = sorted(table)
    sel = p.add("sel " + " ".join(map(str, notes)), 120, 300); p.con(sp, 0, sel, 0)
    out = p.add("outlet", 10, 490)
    for k, nt in enumerate(notes):
        x = 120 + k * 70
        act = table[nt]
        if isinstance(act, tuple):              # twice within a second
            _, msg = act
            t = p.add("t b b", x, 330); p.con(sel, k, t, 0)
            f = p.add("f", x, 360); add = p.add("+ 1", x + 40, 360)
            p.con(t, 1, f, 0); p.con(f, 0, add, 0); p.con(add, 0, f, 1)
            ge = p.add("sel 2 1", x, 390); p.con(add, 0, ge, 0)
            dl = p.add("del 1000", x + 40, 330); p.con(t, 0, dl, 0)
            z = p.msg("0", x + 40, 420); p.con(dl, 0, z, 0); p.con(ge, 0, z, 0); p.con(z, 0, f, 1)
            m = p.msg(msg, x, 450); p.con(ge, 0, m, 0)
            # LED: flashing while armed, steady again after the second press or the timeout
            arm = p.msg(f"{nt} {color(act) + FLASH}", x + 20, 480); p.con(ge, 1, arm, 0)
            dis = p.msg(f"{nt} {color(act)}", x + 20, 500); p.con(z, 0, dis, 0)
            for b in (arm, dis):
                p.con(b, 0, sl, 0)
        else:
            m = p.msg(act, x, 330 + (k % 2) * 30); p.con(sel, k, m, 0)
            if act.split()[0] == "save":        # white for a moment
                ts = p.add("t b b", x + 20, 390); p.con(sel, k, ts, 0)
                w = p.msg(f"{nt} {WHITE}", x + 20, 420); p.con(ts, 1, w, 0)
                dd = p.add(f"del {SAVE_ACK_MS}", x + 20, 445); p.con(ts, 0, dd, 0)
                bk = p.msg(f"{nt} {color(act)}", x + 20, 470); p.con(dd, 0, bk, 0)
                for b in (w, bk):
                    p.con(b, 0, sl, 0)
        p.con(m, 0, out, 0)
    with open(path, "w") as fh:
        fh.write("\n".join(p.lines(top=True)) + "\n")
    return {nt: (a[1] + " (2x)" if isinstance(a, tuple) else a) for nt, a in table.items()}
