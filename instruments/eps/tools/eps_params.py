#!/usr/bin/env python3
"""The controls of eps~ in one table: the header pd/eps_params.h, the controller layer
[epscc], the editor [epsedit] and the help patch are all generated from it.

eps~ plays the instruments of an Ensoniq EPS / EPS-16 PLUS / ASR-10 as they are stored. Its
controls are performance offsets over the loaded instrument (0 = as stored, like the macros
of d50~), kept with a user slot; the settings are not stored.

  kind O   an offset or performance value, stored in a user slot
  kind S   a setting of the instrument, not stored

usage: python3 tools/eps_params.py   (writes pd/eps_params.h)
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# name, kind, lo, hi, default, label (<= 12), value names, help
CONTROL_LIST = [
    ("cut", "O", -63, 63, 0, "Cutoff", "",
     "cutoff of filter 1 of every wavesample, also of sounding notes. 0 leaves the instrument "
     "as it is"),
    ("cut2", "O", -63, 63, 0, "Filter 2", "",
     "cutoff of filter 2 (the second low-pass, or the high-pass in the modes with one), "
     "also of sounding notes. The EPS has no resonance, this takes its place on page 1"),
    ("att", "O", -63, 63, 0, "Attack", "",
     "attack: time 1 of the amp envelope, in steps of the panel's 0-99 times, for the notes "
     "that follow"),
    ("rel", "O", -63, 63, 0, "Release", "",
     "release: times 5 and 6 of the amp envelope, also for notes already held"),
    ("fatt", "O", -63, 63, 0, "F attack", "",
     "attack of the filter envelope (ENV2): time 1, for the notes that follow"),
    ("fdec", "O", -63, 63, 0, "F decay", "",
     "decay of the filter envelope: times 2 to 4, for the notes that follow"),
    ("frel", "O", -63, 63, 0, "F release", "",
     "release of the filter envelope: times 5 and 6, also for notes already held"),
    ("vib", "O", 0, 127, 0, "Vibrato", "",
     "vibrato of eps~ itself (not the instrument's LFO), up to a semitone"),
    ("wave", "O", 0, 127, 0, "Wave pos", "",
     "position of the wave modulation (transwave, loop position): added to the wavesample's "
     "mod source, as if the wheel were turned up. No effect on wavesamples without wave "
     "modulation"),
    ("volume", "S", 0, 127, 100, "Volume", "",
     "master volume, 100 = unity, not stored"),
    ("patch", "O", 0, 3, 0, "Patch sel", "00|0*|*0|**",
     "patch select: which layers play, as the two patch buttons of the EPS"),
    ("transpose", "O", -24, 24, 0, "Transpose", "",
     "transposition in semitones, of the keyboard and the pitch"),
    ("tune", "O", -50, 50, 0, "Tune", "", "fine tuning in cents"),
    ("bend", "O", 0, 12, 2, "Bend range", "", "bender range in semitones"),
    ("dec", "O", -63, 63, 0, "Decay", "",
     "decay: times 2 to 4 of the amp envelope, for the notes that follow"),
    ("fenv", "O", -63, 63, 0, "Filter env", "",
     "added to the filter envelope amount of every wavesample, also of sounding notes"),
    ("vibrate", "O", 0, 127, 50, "Vib rate", "", "rate of the vibrato, 0.1 to 12 Hz"),
    ("xcc", "S", 0, 119, 2, "XCTRL CC", "",
     "the MIDI controller that is the XCTRL mod source (2 = breath, as on the EPS), not stored"),
    ("voices", "S", 1, 32, 20, "Voices", "",
     "polyphony: 20 as on the EPS-16 PLUS, up to the 32 of the ES5505, not stored"),
]

# Controller pages (row k = CC page k of common/tools/ctlayer.py): P1 and P2 of the Launchkey
# surface (tools/eps_pages.py), the same CC numbers for the Bela. P1: the two filters and the
# filter and amp envelopes; P2: volume, transpose, wave position, filter envelope amount.
CC_ROWS = [
    ("PERFORM", ["cut", "cut2", "fatt", "fdec", "frel", "att", "dec", "rel"]),
    ("PLAY", ["volume", "transpose", "wave", "fenv", None, None, None, None]),
]
# Without CC: the editor and the pads (patch select on PAT < >).
EXTRA_ROWS = [
    ("MORE  no CC (editor and pads)", ["patch", "tune", "bend", "vib", "vibrate", "voices", "xcc", None]),
]

# Own pads ([epspads], common/tools/ctpads.py): 36-38 and 44-46 are the same in every
# instrument. eps~: the patch select buttons.
OWN_PADS = {39: "cycle patch", 47: "cycle patch -1"}
OWN_PAD_TEXT = {39: "patch select +", 47: "patch select -"}
ALL_ROWS = CC_ROWS + EXTRA_ROWS

CONTROLS = {}
DEFAULTS = {}
for i, (nm, kind, lo, hi, dflt, lbl, names, hlp) in enumerate(CONTROL_LIST):
    CONTROLS[nm] = (kind, i, lo, hi, lbl, names, hlp)
    DEFAULTS[nm] = dflt

_listed = [n for _, ns in ALL_ROWS for n in ns if n]
assert len(_listed) == len(set(_listed)) and set(_listed) == set(CONTROLS), \
    set(CONTROLS) ^ set(_listed)
ORDER = _listed


def value_names(names, lo, hi):
    if not names:
        return None
    v = names.split("|")
    assert len(v) == hi - lo + 1, (names, lo, hi)
    return v


for _nm, _c in CONTROLS.items():
    value_names(_c[5], _c[2], _c[3])
    assert len(_c[4]) <= 12, _c[4]
    assert _c[2] <= DEFAULTS[_nm] <= _c[3], _nm


def write_header(path):
    L = ["// Generated by tools/eps_params.py -- do not edit.",
         "// name, kind (O offset stored in a user slot, S setting), lowest and highest",
         "// value, default, label, value names",
         "static const Control kControls[] = {"]
    for nm in ORDER:
        kind, i, lo, hi, lbl, names, _ = CONTROLS[nm]
        L.append(f'    {{"{nm}", \'{kind}\', {lo}, {hi}, {DEFAULTS[nm]}, "{lbl}", "{names}"}},')
    L.append("};")
    L.append("")
    L.append("enum Ctl { " + ", ".join(f"kC_{n}" for n in ORDER) + ", kCtlCount };")
    open(path, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    out = os.path.join(ROOT, "pd", "eps_params.h")
    write_header(out)
    print("wrote", out, f"({len(CONTROLS)} controls, {sum(1 for _, n in CC_ROWS for x in n if x)} on CC pages)")
