#!/usr/bin/env python3
"""Write pd/engine/eps_tables.h from tests/calibration/measured.json.

The JSON holds values measured on the original EPS-16 PLUS operating system
(see tests/calibration/README.md). This script only reformats them; the
engine does the interpolation and the conversion to the host sample rate.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
m = json.loads((ROOT / "tests/calibration/measured.json").read_text())


def arr(name, ctype, values, per_line=16, fmt="{}"):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("    " + ", ".join(fmt.format(v) for v in values[i:i + per_line]) + ",")
    return f"constexpr {ctype} {name}[{len(values)}] = {{\n" + "\n".join(lines) + "\n};\n"


# Pan: measured every 8 steps of the signed pan value; fill -128..127 linearly.
pan_pts = sorted((int(k), v) for k, v in m["pan_offset12"].items())
pan_l, pan_r = [], []
for p in range(-128, 128):
    lo = max(k for k, _ in pan_pts if k <= p)
    hi = min(k for k, _ in pan_pts if k >= p)
    a = dict(pan_pts)[lo]
    b = dict(pan_pts)[hi]
    f = 0 if hi == lo else (p - lo) / (hi - lo)
    pan_l.append(round(a[0] + (b[0] - a[0]) * f))
    pan_r.append(round(a[1] + (b[1] - a[1]) * f))

out = [
    "// eps_tables.h - generated by tools/gen_eps_tables.py from",
    "// tests/calibration/measured.json. Do not edit by hand.",
    "//",
    "// " + m["source"],
    "#pragma once",
    "#include <cstdint>",
    "",
    "namespace eps {",
    "namespace tables {",
    "",
    f"constexpr float kChipRate = {m['chip_rate_hz']}.f;   // rate the values below were measured at",
    "",
    "// Filter cutoff 0..150 -> 12-bit K of the ES5505 at kChipRate: the low-pass",
    "// (K1, and K2 in modes 2/3) and the high-pass (K2 in modes 0/1).",
    arr("kLowpassK", "uint16_t", m["cutoff_lowpass_k12"]),
    arr("kHighpassK", "uint16_t", m["cutoff_highpass_k12"]),
    "// Wavesample volume / envelope level 0..127 -> 12-bit volume code",
    "// (4-bit exponent, 4-bit mantissa, 4 bits of fraction; 0x100 = 6 dB).",
    arr("kVolumeCode", "uint16_t", m["volume_code12"]),
    "// Signed pan -128..127 -> volume code offsets left / right.",
    arr("kPanLeft", "int16_t", pan_l),
    arr("kPanRight", "int16_t", pan_r),
    f"constexpr int kBoostCode = {m['boost_code12']};          // BOOST on: +12 dB",
    f"constexpr int kAttackKneeCode = {m['amp_attack_knee_code12']};      // see the amp envelope",
    "",
    "// Envelope time 0..99 -> milliseconds a segment takes, whatever its levels.",
    arr("kEnvMs", "float", m["env_time_ms"], 10, "{:.1f}f"),
    "} // namespace tables",
    "} // namespace eps",
    "",
]
(ROOT / "pd/engine/eps_tables.h").write_text("\n".join(out))
print("wrote pd/engine/eps_tables.h")
