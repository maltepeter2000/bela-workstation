#!/usr/bin/env python3
"""Writes pd/engine/juno/juno_decim.h: the decimation filter of juno~ for 2x and 4x
oversampling, an 8th-order elliptic low-pass as four biquads.

The corners are fractions of the output rate fb, so the same coefficients serve 44.1, 48 or
96 kHz: flat (0.1 dB ripple) to 0.42 fb, which is 20.2 kHz at 48 kHz, and at least 80 dB down
from about 0.57 fb on -- everything that would fold back below 0.43 fb.

usage: python3 tools/make_juno_decim.py      (needs scipy)
"""
import os
import numpy as np
from scipy import signal

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "pd", "engine", "juno", "juno_decim.h")
DESIGN = {2: 90, 4: 80}        # stopband attenuation in dB for each factor

L = ["/* Generated by tools/make_juno_decim.py -- do not edit. juno~ addition.",
     " * Decimation low-pass: 8th-order elliptic, flat to 0.42 of the output rate,",
     " * >= 80 dB down from about 0.57 of it. Four biquads, b0 b1 b2 a1 a2 (a0 = 1). */",
     "#ifndef JUNO_DECIM_H", "#define JUNO_DECIM_H", ""]
for os_, rs in DESIGN.items():
    sos = signal.ellip(8, 0.1, rs, 0.42 * 2 / os_, output="sos")
    w, h = signal.sosfreqz(sos, worN=100000, fs=os_)
    H = 20 * np.log10(np.abs(h) + 1e-15)
    stop = w[np.argmax((w > 0.42) & (H < -rs + 0.5))]
    L.append(f"/* {os_}x: stopband {rs} dB from {stop:.3f} of the output rate */")
    L.append(f"static const float kJunoDecim{os_}[4][5] = {{")
    for s in sos:
        b, a = s[:3], s[3:]
        L.append("    {" + ", ".join(f"{v:.10e}f" for v in (b[0], b[1], b[2], a[1], a[2])) + "},")
    L.append("};")
    L.append("")
L.append("#endif")
open(OUT, "w").write("\n".join(L) + "\n")
print("wrote", os.path.normpath(OUT))
